-- Кадр 17c «Детектор плача» — точность по причинам и порог уверенности.
--
-- ЧЕГО НЕ ХВАТАЛО. `cry_results` хранит, что классификатор ОТВЕТИЛ: причину и
-- уверенность. Чего в базе нет ни в каком виде — было ли это правдой. Поэтому
-- любая «точность», посчитанная из имеющихся строк, была бы точностью модели
-- по её собственному мнению о себе: средняя уверенность, переименованная в
-- accuracy. Панель, которая печатает такую цифру рядом со словом «точность»,
-- врёт спокойно и убедительно, и именно из неё потом принимают решение
-- поднять или опустить порог.
--
-- Отсюда две колонки ниже. Единственный человек, который знает, почему малыш
-- плакал, — мама, которая через минуту его покормила. `verdict` — её ответ на
-- вопрос «это было верно?»; `actual_reason` — что было на самом деле, если
-- нет. Обе NULL, и NULL — это не «неверно», а «не спрашивали / не ответила».
-- Все три состояния считаются отдельно: доля правильных берётся ТОЛЬКО по
-- оценённым строкам, а сколько строк вообще не оценено, панель пишет рядом.
--
-- ЧЕГО ЗДЕСЬ НЕТ. Самой записи. Клип уходит на классификатор и не сохраняется
-- нигде (см. __tests__/cryNotStored.test.ts), так что «послушать запись» из
-- панели невозможно и никогда не станет возможным без отдельного, честно
-- спрошенного согласия. Панель говорит это словами вместо того, чтобы рисовать
-- неработающую кнопку «прослушать».

-- Ответ мамы на конкретный разбор. 'correct' | 'wrong'.
-- NULL = не оценивали: третье состояние, а не «неверно».
ALTER TABLE cry_results
  ADD COLUMN IF NOT EXISTS verdict TEXT;
ALTER TABLE cry_results
  ADD COLUMN IF NOT EXISTS actual_reason TEXT;

-- Проверка отдельным шагом: ADD COLUMN IF NOT EXISTS не умеет добавлять
-- ограничение к уже существующей колонке, а миграция должна быть повторяемой.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'cry_results_verdict_check'
  ) THEN
    ALTER TABLE cry_results
      ADD CONSTRAINT cry_results_verdict_check
      CHECK (verdict IS NULL OR verdict IN ('correct','wrong'));
  END IF;
END $$;

-- «Порог 45 %» из кадра.
--
-- Ниже порога приложение НЕ НАЗЫВАЕТ причину: экран говорит «не уверены»,
-- оставляет столбики вероятностей и просит записать ещё раз. До этой таблицы
-- порог был константой в Dart — то есть изменить его значило выпустить релиз в
-- сторы, а «модель стала хуже на шумных записях» — это ситуация ближайших
-- недель, а не следующего квартала.
--
-- Одна строка, как vaccination_settings: порог у детектора один, не по одному
-- на причину. Пять причин с пятью порогами — это пять решений, которые никто
-- не сможет обосновать по отдельности, пока нет ни одной оценки.
CREATE TABLE IF NOT EXISTS cry_settings (
  id             BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (id),
  -- 0..0.95. Верхняя граница не 1: порог, которого не достигает ни один ответ,
  -- выключает экран целиком, и сделать это одним неверным вводом в поле
  -- «доля» слишком легко.
  min_confidence REAL NOT NULL CHECK (min_confidence >= 0 AND min_confidence <= 0.95),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- Какой сотрудник. Nullable, потому что колонка переживает учётные записи.
  updated_by     TEXT
);
